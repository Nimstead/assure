"""Which curated Windows apps were proven on a real VM, from the run files themselves (W13: every app labelled).

  uv run python ../sandbox/winapps_evidence.py     (from api/; rewrites api/src/nimstead/winapps_evidence.py)

proven: winget installed an old version and upgraded it on a real VM, and the agent identified both from the registry
(winapps_e2e.py's "proven"). real name: the agent identified it from a real install's registry entry, but no upgrade was
proven. Every other curated key is matched from its name pattern only.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api" / "src"))
from nimstead import winapps  # noqa: E402


def identified(node, out: set) -> None:
    """Add first identified-list values from nested dictionaries/lists to mutable set out.

    node is decoded run data. Values are coerced to strings. No file I/O occurs.
    Unsupported leaf types are ignored. Cyclic containers can raise RecursionError.
    """
    if isinstance(node, dict):
        if isinstance(node.get("identified"), list) and node["identified"]:
            out.add(str(node["identified"][0]))
        for v in node.values():
            identified(v, out)
    elif isinstance(node, list):
        for v in node:
            identified(v, out)


def derive() -> dict[str, tuple[str, list[str]]]:
    """Return curated keys mapped to (historical evidence label, sorted run filenames).

    Read sandbox/last_run_win*.json under ROOT. Derive proven from reported flags
    or changed identified versions. Otherwise retain real name observations.
    Keys with neither observation are omitted. No files are written by this function.
    File, JSON and malformed nested-data errors propagate. Labels do not rerun VMs.
    """
    proven, real = {}, {}
    for f in sorted((ROOT / "sandbox").glob("last_run_win*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            continue
        for app in (data.get("apps") or {}).values():
            keys: set = set()
            identified(app, keys)
            for k in keys:
                (proven if isinstance(app, dict) and app.get("proven") else real).setdefault(k, set()).add(f.name)
            # batch 8 wrote its rows from these real entries after the run: today's rows read them as the agent would
            if isinstance(app, dict):
                ids = {side: {winapps.identify(*e) for e in app.get(side) or [] if isinstance(e, list) and len(e) == 3} - {None}
                       for side in ("entries_old", "entries_new")}
                for k, v in ids["entries_old"]:
                    newer = {nv for nk, nv in ids["entries_new"] if nk == k}
                    (proven if newer and v not in newer else real).setdefault(k, set()).add(f.name)
        keys = set()
        identified(data, keys)
        for k in keys:
            real.setdefault(k, set()).add(f.name)
        # winnoise.py: the curated keys the agent matched at the old versions, and again after the upgrade
        before = ((data.get("old") or {}).get("products") or {}) if isinstance(data.get("old"), dict) else {}
        after = ((data.get("updated") or {}).get("products") or {}) if isinstance(data.get("updated"), dict) else {}
        for k, versions in before.items():
            moved = k in after and set(map(str, after[k])) != set(map(str, versions))
            (proven if moved else real).setdefault(k, set()).add(f.name)
    curated = {p.key for p in winapps.PRODUCTS}
    out = {}
    for k in sorted(curated):
        if k in proven:
            out[k] = ("proven", sorted(proven[k]))
        elif k in real:
            out[k] = ("real name", sorted(real[k]))
    return out


if __name__ == "__main__":
    ev = derive()
    lines = ['"""Generated by sandbox/winapps_evidence.py from the run files: do not edit. key -> (evidence, run files)."""', "",
             "EVIDENCE: dict[str, tuple[str, tuple[str, ...]]] = {"]
    lines += [f"    {k!r}: ({v[0]!r}, {tuple(v[1])!r})," for k, v in ev.items()]
    lines += ["}", ""]
    (ROOT / "api" / "src" / "nimstead" / "winapps_evidence.py").write_text("\n".join(lines), encoding="utf-8")
    curated = len({p.key for p in winapps.PRODUCTS})
    print(f"{curated} curated; proven {sum(v[0] == 'proven' for v in ev.values())}, real name {sum(v[0] == 'real name' for v in ev.values())}, "
          f"pattern only {curated - len(ev)}")
